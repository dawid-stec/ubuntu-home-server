#!/usr/bin/env python3
"""Sync application Public Hostnames to the Cloudflare Tunnel via API.

Source of truth: .deploy/apps.tsv (generated by generate_compose.py) and
PUBLIC_HOSTNAME in env/<app>.env on the server. Without CF_* configuration
this script only prints desired routes and exits successfully. Local deploy
then works without Cloudflare automation.

Required variables (main .env): CF_API_TOKEN, CF_ACCOUNT_ID, CF_TUNNEL_ID.
Optional: CF_ZONE_ID globally, or per app in env/<app>.env. Without a zone
id, DNS record sync is skipped (tunnel ingress is still set).

Create the API token once in the Cloudflare dashboard (My Profile ->
API Tokens) with permissions: Account -> Cloudflare Tunnel -> Edit and
Zone -> DNS -> Edit for zones in use.
"""
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://api.cloudflare.com/client/v4"


def merge_ingress(existing, desired):
    """Merge tunnel ingress: app entries replace same hostnames, foreign
    entries stay, catch-all http_status:404 always last."""
    desired_hosts = {d["hostname"] for d in desired}
    kept = [
        e for e in existing
        if e.get("hostname") not in desired_hosts and e.get("service") != "http_status:404"
    ]
    return kept + desired + [{"service": "http_status:404"}]


def load_apps(tsv_path):
    rows = []
    lines = Path(tsv_path).read_text(encoding="utf-8").splitlines()
    for line in lines[1:]:
        parts = line.split("\t")
        if len(parts) < 6:
            continue
        repo, service, port, _health, hostname, zone = parts[:6]
        if hostname:
            rows.append({
                "hostname": hostname,
                "service": f"http://{service}:{port}",
                "zone_id": zone,
            })
    return rows


class CfApi:
    def __init__(self, token):
        self.token = token

    def call(self, method, path, payload=None):
        req = urllib.request.Request(
            API + path,
            method=method,
            data=json.dumps(payload).encode() if payload is not None else None,
            headers={
                "Authorization": f"Bearer {self.token}",
                "Content-Type": "application/json",
            },
        )
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                body = json.loads(resp.read().decode())
        except urllib.error.HTTPError as e:
            detail = e.read().decode(errors="replace")
            try:
                errors = json.loads(detail).get("errors") or detail
            except json.JSONDecodeError:
                errors = detail
            hint = ""
            if e.code == 404 and "/zones/" in path:
                hint = (" - zone with this CF_ZONE_ID does not exist or token has no access"
                        " (check domain Zone ID and token Zone Resources)")
            raise RuntimeError(f"Cloudflare API {method} {path}: HTTP {e.code}: {errors}{hint}") from None
        if not body.get("success"):
            raise RuntimeError(f"Cloudflare API {method} {path}: {body.get('errors')}")
        return body["result"]


def sync_dns(api, zone_id, hostname, tunnel_id):
    target = f"{tunnel_id}.cfargotunnel.com"
    query = urllib.parse.urlencode({"type": "CNAME", "name": hostname})
    records = api.call("GET", f"/zones/{zone_id}/dns_records?{query}")
    payload = {"type": "CNAME", "name": hostname, "content": target, "proxied": True}
    if not records:
        api.call("POST", f"/zones/{zone_id}/dns_records", payload)
        print(f"    DNS: created CNAME {hostname} -> {target}")
    elif records[0].get("content") != target or not records[0].get("proxied"):
        api.call("PUT", f"/zones/{zone_id}/dns_records/{records[0]['id']}", payload)
        print(f"    DNS: updated CNAME {hostname}")


def main(argv=None):
    root = Path(__file__).resolve().parent.parent
    tsv = root / ".deploy" / "apps.tsv"
    if not tsv.is_file():
        print("Missing .deploy/apps.tsv - run generate_compose.py first.", file=sys.stderr)
        return 1
    desired = load_apps(tsv)
    if not desired:
        print("  No application has PUBLIC_HOSTNAME - skipping Cloudflare.")
        return 0

    token = os.environ.get("CF_API_TOKEN", "")
    account = os.environ.get("CF_ACCOUNT_ID", "")
    tunnel = os.environ.get("CF_TUNNEL_ID", "")
    if not (token and account and tunnel):
        print("  Cloudflare: no CF_API_TOKEN/CF_ACCOUNT_ID/CF_TUNNEL_ID in .env - skipping sync.")
        print("  Desired Public Hostnames (set manually if needed):")
        for d in desired:
            print(f"    {d['hostname']} -> {d['service']}")
        return 0

    api = CfApi(token)
    try:
        return _sync(api, account, tunnel, desired)
    except RuntimeError as e:
        print(f"  Cloudflare: {e}", file=sys.stderr)
        return 1


def _sync(api, account, tunnel, desired):
    base = f"/accounts/{account}/cfd_tunnel/{tunnel}/configurations"
    current = api.call("GET", base)
    existing = (current or {}).get("config", {}).get("ingress", []) or []
    ingress = merge_ingress(existing, [{"hostname": d["hostname"], "service": d["service"]} for d in desired])
    if ingress != existing:
        api.call("PUT", base, {"config": {"ingress": ingress}})
        print("  Cloudflare: tunnel ingress updated.")
    else:
        print("  Cloudflare: tunnel ingress unchanged.")

    default_zone = os.environ.get("CF_ZONE_ID", "")
    for d in desired:
        zone = d["zone_id"] or default_zone
        if zone:
            sync_dns(api, zone, d["hostname"], tunnel)
        else:
            print(f"    DNS: skipping {d['hostname']} (no CF_ZONE_ID)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
